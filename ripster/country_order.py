"""Общий порядок стран по часовым зонам для приоритета учёток.

Релизы выходят в пятницу по местному времени витрины. Новая Зеландия (UTC+12/13)
видит новый день на сутки раньше, чем США (UTC-5/-8). Поэтому учётка NZ
проверяется первой: если релиз уже доступен в NZ, не надо дёргать US.

Порядок: от самых восточных часовых зон (где раньше наступает новый день)
к западным. Кирибати (UTC+14) → NZ (UTC+12/+13) → AU (UTC+8/+10:30) →
JP/SG/KR (UTC+8/+9) → IN (UTC+5:30) → AE (UTC+4) → RU/TR (UTC+3) →
ZA/EG (UTC+2) → DE/FR/IT (UTC+1/+2) → GB/IE/PT (UTC+0/+1) → IS (UTC+0) →
BR/AR (UTC-3) → CA/US-east (UTC-5/-4) → US-west (UTC-8) → HI (UTC-10).

Используется в Tidal, Deezer, Qobuz — сервисах, где витрина зависит от страны.
Spotify, SoundCloud, Yandex, Apple — без country_rank (глобальные или один регион).
"""
from __future__ import annotations


#: Полный список стран по UTC offset (от +14 до -10).
#: Чем МЕНЬШЕ индекс, тем раньше витрина получает релиз.
COUNTRY_ORDER = (
    # Океания (UTC+12/+14): первые видят новый день
    "KI", "NZ", "FJ", "TO",
    # Австралия (UTC+8/+10:30)
    "AU",
    # Восточная Азия (UTC+8/+9)
    "JP", "KR", "SG", "TW", "HK", "PH", "TH", "MY", "ID",
    # Южная Азия (UTC+5:30)
    "IN",
    # Ближний Восток (UTC+3/+4)
    "AE", "SA", "IL",
    # Восточная Европа/Россия (UTC+2/+3)
    "RU", "TR", "UA", "PL",
    # Южная Африка (UTC+2)
    "ZA", "EG",
    # Западная Европа (UTC+1/+2)
    "DE", "FR", "IT", "ES", "NL", "BE", "AT", "CH", "SE", "NO", "DK", "FI",
    # Великобритания/Ирландия (UTC+0/+1)
    "GB", "IE", "PT",
    # Исландия (UTC+0)
    "IS",
    # Южная Америка (UTC-3)
    "BR", "AR", "CL", "CO", "PE",
    # Северная Америка восток (UTC-5/-4)
    "CA", "US", "MX",
    # Гавайи (UTC-10): последние видят новый день
    "PR",
)


def country_rank(country: str, order: tuple[str, ...] | None = None) -> int:
    """Насколько рано витрина этой страны отдаёт новинки.

    Меньше число = раньше видят релиз. NZ = 1, US = 45-46.
    Неизвестная страна = len(order) + 1 (после всех известных).
    Пустая страна = len(order) (в середину, не в конец).

    `order` — переопределение порядка из конфига (если владелец решит иначе).
    """
    order = order or COUNTRY_ORDER
    cc = (country or "").strip().upper()
    if not cc:
        return len(order)
    return order.index(cc) if cc in order else len(order) + 1
