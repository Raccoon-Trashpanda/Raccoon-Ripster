// Полифазный ресемплер (windowed-sinc). Пункт a5 трекера.
//
// ЧЕМ БЫЛ ПЛОХ ЛИНЕЙНЫЙ, КОТОРЫЙ ЗДЕСЬ СТОЯЛ
//
// Не только «звучит хуже». У него два дефекта, и второй хуже первого:
//
//  1. Линейная интерполяция — это фильтр с завалом и с огромным пропусканием
//     за полосой. При 96 → 48 кГц всё, что выше 24 кГц, складывается обратно
//     в слышимую полосу; на музыке это шершавость на верхах, которую легко
//     принять за «такая запись».
//
//  2. ПОЗИЦИЯ НЕ ПЕРЕНОСИЛАСЬ МЕЖДУ БЛОКАМИ. `srcPos` начинался с нуля на
//     каждом блоке декодера, а последний отсчёт блока дублировался
//     (`i1 = min(i0+1, got-1)`). То есть на каждой границе блока фаза
//     прыгала и сигнал получал разрыв — это ровно «щелчки на границах» из
//     каталога чужих ошибок (a7), только свои собственные. Слышно как
//     регулярное потрескивание, тем чаще, чем меньше блок.
//
// КАК СДЕЛАНО ЗДЕСЬ
//
// Прототип — sinc, окно Кайзера. Ядро посчитано заранее в таблицу фаз:
// [PHASES][TAPS]. Для выходного отсчёта берётся ближайшая фаза, и это
// умножение вектора на вектор — никакой тригонометрии в реальном времени.
//
// Срез двигается вместе с отношением частот: при ПОНИЖЕНИИ частоты полосу
// надо резать по НОВОЙ частоте Найквиста, иначе понижение само и создаёт
// зеркала. Отсюда `cutoff = 0.92 * min(1, ratio)`.
//
// Хвост входа (TAPS отсчётов) переносится в следующий вызов вместе с дробной
// позицией — поэтому границ блоков в звуке не слышно вовсе.
//
// Файл намеренно без Android: тот же заголовок пойдёт в ПК-тракт.
#pragma once

#include <cmath>
#include <cstdint>
#include <cstring>
#include <vector>

namespace rsmp {

// 32 отвода на фазу и 128 фаз: при 24-битном материале ошибка фазовой
// квантизации уходит ниже уровня собственного шума записи, а таблица
// остаётся 16 КБ — она живёт в кэше процессора.
constexpr int kTaps = 32;
constexpr int kPhases = 128;
constexpr int kHalf = kTaps / 2;

inline double bessel_i0(double x) {
    // Ряд для модифицированной функции Бесселя. Двадцати членов хватает с
    // запасом на нужный диапазон β; считается один раз при построении окна.
    double s = 1.0, t = 1.0;
    for (int k = 1; k < 20; ++k) {
        t *= (x / 2.0) * (x / 2.0) / (double) (k * k);
        s += t;
        if (t < 1e-16 * s) break;
    }
    return s;
}

/** Таблица ядра под конкретное отношение частот. */
struct Kernel {
    std::vector<float> t;      // [phase][tap]
    double cutoff = 1.0;

    void build(double ratio) {
        // ratio = выходная частота / входная. Меньше единицы — понижаем.
        cutoff = 0.92 * (ratio < 1.0 ? ratio : 1.0);
        // Одна лишняя фаза в конце: последняя смешивается со следующей,
        // и без запаса пришлось бы заворачивать индекс на нулевую — она
        // соответствует другому отсчёту, и на стыке был бы скачок.
        t.assign((size_t) (kPhases + 1) * kTaps, 0.0f);
        const double beta = 8.6;               // ~ -80 дБ за полосой
        const double i0b = bessel_i0(beta);
        for (int p = 0; p <= kPhases; ++p) {
            const double frac = (double) p / kPhases;
            double sum = 0.0;
            for (int k = 0; k < kTaps; ++k) {
                // Отсчёт ядра относительно текущей позиции: центр между
                // kHalf-1 и kHalf, сдвинутый на дробную часть.
                const double x = (double) (k - kHalf + 1) - frac;
                const double s = (std::fabs(x) < 1e-9)
                                 ? cutoff
                                 : std::sin(M_PI * cutoff * x) / (M_PI * x);
                const double r = 2.0 * (double) k / (kTaps - 1) - 1.0;
                const double w = bessel_i0(beta * std::sqrt(std::fabs(1.0 - r * r))) / i0b;
                const double v = s * w;
                t[(size_t) p * kTaps + k] = (float) v;
                sum += v;
            }
            // Нормируем КАЖДУЮ фазу отдельно: иначе громкость гуляла бы от
            // фазы к фазе, и на выходе появлялась бы модуляция на разностной
            // частоте — тихий, но слышимый «фон».
            if (sum > 1e-12) {
                for (int k = 0; k < kTaps; ++k) t[(size_t) p * kTaps + k] /= (float) sum;
            }
        }
    }
};

/**
 * Состояние потока. Один экземпляр на дорожку: хранит хвост входа и дробную
 * позицию, поэтому блоки склеиваются без разрывов.
 */
class Resampler {
public:
    void reset(int channels, double inRate, double outRate) {
        ch_ = channels > 0 ? channels : 2;
        ratio_ = (inRate > 0.0) ? outRate / inRate : 1.0;
        kern_.build(ratio_);
        hist_.assign((size_t) kTaps * ch_, 0.0f);
        // Начинаем с первого НАСТОЯЩЕГО отсчёта: история пока нулевая,
        // и читать из неё нечего.
        pos_ = (double) kTaps;
        primed_ = false;
    }

    bool passthrough() const { return std::fabs(ratio_ - 1.0) < 1e-9; }

    /** Сколько максимум выйдет из [inFrames] входных кадров. */
    int64_t maxOut(int64_t inFrames) const {
        return (int64_t) ((double) (inFrames + kTaps) * ratio_) + 2;
    }

    /**
     * Преобразовать блок. Возвращает число выходных кадров.
     *
     * Вход и выход интерливнутые. Хвост входа запоминается сам — вызывающему
     * не нужно ничего склеивать.
     */
    int64_t process(const float* in, int64_t inFrames, float* out, int64_t outCap) {
        if (inFrames <= 0) return 0;
        // Склеиваем историю и новый блок: ядро смотрит назад на kHalf отсчётов,
        // и без истории каждый блок начинался бы с нулей — это и есть щелчок.
        buf_.resize((size_t) (kTaps + inFrames) * ch_);
        std::memcpy(buf_.data(), hist_.data(), sizeof(float) * (size_t) kTaps * ch_);
        std::memcpy(buf_.data() + (size_t) kTaps * ch_, in,
                    sizeof(float) * (size_t) inFrames * ch_);

        const int64_t avail = kTaps + inFrames;      // кадров в buf_

        // ПОЗИЦИЯ СЧИТАЕТСЯ В КООРДИНАТАХ buf_, И ЭТО ВАЖНО.
        //
        // Первая версия пыталась держать в `pos_` только дробную часть и
        // доправлять её разностью «сколько съели минус сколько дали». Числа
        // там были целые и большие, дробная часть уезжала на десятки, чтение
        // прыгало по буферу — на выходе получался шум вместо тона (замер:
        // амплитуда 0.012 вместо 0.5) и расхождение при разной нарезке.
        //
        // Правильно проще: `pos_` — это позиция СЛЕДУЮЩЕГО выходного отсчёта
        // в координатах текущего буфера. В конце вызова мы оставляем последние
        // kTaps кадров как новую историю, то есть начало буфера сдвигается на
        // (avail - kTaps) — ровно на столько и уменьшается позиция.
        double p = pos_;
        const double step = 1.0 / ratio_;
        int64_t n = 0;
        while (n < outCap) {
            const int64_t i = (int64_t) p;
            // Ядру нужны отсчёты i-kHalf+1 … i+kHalf: и слева, и справа.
            if (i + kHalf >= avail) break;
            if (i < kHalf - 1) { p += step; continue; }
            const double frac = p - (double) i;
            // ФАЗУ ИНТЕРПОЛИРУЕМ, А НЕ ОКРУГЛЯЕМ.
            //
            // Таблица дискретна (kPhases штук), и если брать ближайшую фазу,
            // остаётся ступенька: соседние фазы отличаются на 1/kPhases
            // отсчёта, и на выходе это шум квантования фазы. Замер показал его
            // прямо: один и тот же сигнал, поданный разной нарезкой, расходился
            // на 5.5e-4 — не разрыв (их нет), а именно перескок на соседнюю
            // фазу от разницы в последнем знаке. Для 24-битного материала
            // 5.5e-4 это примерно -65 дБ, то есть ВЫШЕ собственного шума
            // записи; для тракта, который называется bit-perfect, так нельзя.
            //
            // Линейная смесь двух соседних фаз убирает ступеньку целиком и
            // стоит одного дополнительного умножения на отвод.
            const double ppos = frac * kPhases;
            const int ph = (int) ppos & (kPhases - 1);
            const int ph2 = ph + 1;      // запасная фаза в таблице есть
            const float mix = (float) (ppos - (double) (int) ppos);
            const float* k0 = &kern_.t[(size_t) ph * kTaps];
            const float* k1 = &kern_.t[(size_t) ph2 * kTaps];
            const int64_t base = i - kHalf + 1;
            for (int c = 0; c < ch_; ++c) {
                float acc = 0.0f;
                const float* x = buf_.data() + (size_t) base * ch_ + c;
                for (int j = 0; j < kTaps; ++j)
                    acc += (k0[j] + mix * (k1[j] - k0[j])) * x[(size_t) j * ch_];
                out[(size_t) n * ch_ + c] = acc;
            }
            ++n;
            p += step;
        }

        // Хвост входа — в историю, позиция — в координаты нового буфера.
        const int64_t shift = avail - kTaps;
        std::memcpy(hist_.data(), buf_.data() + (size_t) shift * ch_,
                    sizeof(float) * (size_t) kTaps * ch_);
        pos_ = p - (double) shift;
        // Страховка: позиция не должна уходить назад в историю дальше, чем
        // хватает ядру, иначе следующий блок начнёт с нулей.
        if (pos_ < (double) (kHalf - 1)) pos_ = (double) (kHalf - 1);
        return n;
    }

private:
    int ch_ = 2;
    double ratio_ = 1.0;
    double pos_ = 0.0;
    bool primed_ = false;
    Kernel kern_;
    std::vector<float> hist_;
    std::vector<float> buf_;
};

}  // namespace rsmp
